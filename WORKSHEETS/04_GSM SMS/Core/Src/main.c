void send_sms(const char *num, const char *text)
{
  char buf[64];
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT\r\n", 4, 500); HAL_Delay(200);
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT+CMGF=1\r\n", 11, 500); HAL_Delay(200);

  snprintf(buf, sizeof(buf), "AT+CMGS=\"%s\"\r\n", num);
  HAL_UART_Transmit(&huart2, (uint8_t*)buf, strlen(buf), 500);
  HAL_Delay(200);

  HAL_UART_Transmit(&huart2, (uint8_t*)text, strlen(text), 500);
  uint8_t ctrlz = 26;
  HAL_UART_Transmit(&huart2, &ctrlz, 1, 500);
}

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_USART2_UART_Init();

  uint8_t last=1;
  while (1)
  {
    uint8_t s = HAL_GPIO_ReadPin(BTN_PORT, BTN_PIN);
    if (s == GPIO_PIN_RESET && last == GPIO_PIN_SET)
    {
      send_sms("+911234567890", "ALERT!");
      HAL_Delay(1000);
    }
    last = s;
  }
  /* USER CODE END 3 */
}

